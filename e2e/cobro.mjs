// Cobro en línea y facturas: sin conectar lo explica; la configuración no acepta llaves inválidas; ya conectado
// (llaves de prueba sembradas) muestra la liga pendiente, el aviso de modo de prueba y la factura.
// Uso: node e2e/cobro.mjs [base] [capturas]   (con SEMBRAR="comando que corre e2e/cobro_sembrar.py")
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import { execSync } from "node:child_process";
const { chromium } = createRequire(import.meta.url)("playwright");
const base = process.argv[2] || "http://localhost:3000";
const dir = process.argv[3] || "./capturas";
mkdirSync(dir, { recursive: true });
const ok = (c, m) => { if (!c) throw new Error("FALLÓ: " + m); console.log("ok  " + m); };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1366, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem("nomira:bienvenida", "1"));
const p = await ctx.newPage();
const errores = [];
p.on("pageerror", (e) => errores.push(String(e)));
await p.goto(base + "/login");
await p.getByLabel("Correo electrónico").first().fill("admin@demo.local");
await p.getByLabel(/Contraseña/).first().fill("Demo-Quincena-2025");
await p.getByRole("button", { name: "Entrar", exact: true }).click();
await p.waitForURL(/\/app/);
await p.goto(base + "/clientes");
const primero = p.locator("tbody tr td a").first();
await primero.waitFor();
await primero.click();
const tarjeta = p.getByRole("region", { name: "Cobro en línea y facturas" });
await tarjeta.getByText(/Conecta tu cuenta de/).waitFor();
ok(true, "sin conectar, la ficha explica cómo activar el cobro y la factura");
const ficha = p.url();
await tarjeta.getByRole("link", { name: "Configurar" }).click();
await p.getByRole("heading", { name: "Cobro en línea y facturación" }).waitFor();
await p.getByLabel("Clave de Stripe").fill("pk_live_publica");
await p.getByRole("button", { name: "Conectar Stripe" }).click();
await p.getByText(/debe empezar con rk_live_/).waitFor();
ok(true, "rechaza una llave que no es secreta ni restringida");
ok(await p.getByLabel("Clave de Stripe").getAttribute("type") === "password", "la llave se escribe oculta");
await p.screenshot({ path: `${dir}/cb-01-configuracion.png`, fullPage: true });
const nombre = execSync(process.env.SEMBRAR).toString().trim();
await p.goto(ficha);
await tarjeta.getByText("Esperando pago").waitFor();
ok(await tarjeta.getByText(/Modo de prueba/).count() === 1, "avisa que está en modo de prueba");
ok(await tarjeta.getByRole("button", { name: "Copiar liga" }).count() === 1, "la liga pendiente se puede copiar");
ok(await tarjeta.getByRole("link", { name: "Mandar por WhatsApp" }).getAttribute("href").then((h) => h.startsWith("https://wa.me/?text=")), "liga lista para WhatsApp");
ok(await tarjeta.getByText("Vigente").count() === 1 && await tarjeta.getByRole("button", { name: "PDF" }).count() === 1, "factura con PDF y XML");
await p.screenshot({ path: `${dir}/cb-02-ficha.png`, fullPage: true });
await p.goto(base + "/clientes/cobro");
ok(await p.getByText(/Conectado · modo de prueba/).count() === 2, "configuración muestra ambas cuentas conectadas, sin la llave completa");
ok(!(await p.content()).includes("e2ee2ee2ee2ee2e"), "la llave completa no aparece en la página");
ok(!errores.length, "sin errores de JavaScript " + errores.join(" "));
console.log("cliente:", nombre);
await b.close();
