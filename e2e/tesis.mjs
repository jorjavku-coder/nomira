// Tesis del SJF: el panel carga un PDF con el formato semanal de la SCJN (tesis FICTICIAS de prueba); un despacho las busca
// sin acentos, lee una, ve la liga oficial y descarga la ficha; el Asistente ofrece «Investigar con tesis».
// Uso: node e2e/tesis.mjs [base] [capturas]
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
const { chromium } = createRequire(import.meta.url)("playwright");
const base = process.argv[2] || "http://localhost:3000";
const dir = process.argv[3] || "./capturas";
mkdirSync(dir, { recursive: true });
const ok = (c, m) => { if (!c) throw new Error("FALLÓ: " + m); console.log("ok  " + m); };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1366, height: 900 }, acceptDownloads: true });
await ctx.addInitScript(() => localStorage.setItem("nomira:bienvenida", "1"));
const errores = [];
const pl = await ctx.newPage();
pl.on("pageerror", (e) => errores.push(String(e)));
await pl.goto(base + "/plataforma/login");
await pl.getByLabel(/Correo/).fill("dueno@nomira.test");
await pl.getByLabel(/Contraseña/).first().fill("Panel-Nomira-2026");
await pl.getByRole("button", { name: /Entrar/ }).click();
await pl.getByRole("link", { name: /Tesis \(SJF\)/ }).click();
await pl.getByRole("heading", { name: "Tesis del Semanario (SJF)" }).waitFor();
await pl.getByLabel("Archivo de tesis").setInputFiles(new URL("./fixtures/tesis_semanal_ejemplo.pdf", import.meta.url).pathname);
await pl.getByRole("button", { name: "Cargar tesis" }).click();
await pl.getByText("Se cargaron 2 tesis.").waitFor();
ok(await pl.getByText(/PDF semanal: 2/).count() === 1, "el panel carga el PDF semanal y cuenta por origen");
await pl.screenshot({ path: `${dir}/ts-01-panel.png`, fullPage: true });

const p = await ctx.newPage();
p.on("pageerror", (e) => errores.push(String(e)));
await p.goto(base + "/login");
await p.getByLabel("Correo electrónico").first().fill("admin@demo.local");
await p.getByLabel(/Contraseña/).first().fill("Demo-Quincena-2025");
await p.getByRole("button", { name: "Entrar", exact: true }).click();
await p.waitForURL(/\/app/);
await p.getByRole("link", { name: "Tesis (SJF)" }).click();
await p.getByLabel("Buscar tesis").fill("suspension clausura");
await p.getByText(/^1 resultado/).waitFor();
ok(true, "busca sin acentos");
await p.getByRole("button", { name: "Leer completa" }).click();
const dlg = p.getByRole("dialog");
await dlg.getByText(/No es una tesis real/).waitFor();
ok(await dlg.getByRole("link", { name: /Ver en el Semanario/ }).getAttribute("href") === "https://sjf2.scjn.gob.mx/detalle/tesis/999001", "liga oficial al Semanario");
const [descarga] = await Promise.all([p.waitForEvent("download"), dlg.getByRole("button", { name: "Descargar ficha PDF" }).click()]);
ok(descarga.suggestedFilename() === "tesis-999001.pdf", "descarga la ficha PDF");
await p.screenshot({ path: `${dir}/ts-02-tesis.png` });
await dlg.getByRole("button", { name: "Cerrar" }).first().click();
await p.getByLabel("Tipo").selectOption("jurisprudencia");
await p.getByLabel("Buscar tesis").fill("prescripcion");
await p.getByText(/JURISPRUDENCIA DE EJEMPLO/).waitFor();
ok(true, "filtra por jurisprudencia");
await p.goto(base + "/asistente");
await p.getByRole("tab", { name: /Investigar con tesis/ }).click();
await p.getByText(/biblioteca de 2 tesis/).waitFor();
ok(true, "el Asistente ofrece investigar con la biblioteca");
await p.getByRole("tab", { name: /Redactar un escrito/ }).click();
ok(await p.getByLabel(/Fundamentar con tesis/).isEnabled(), "opción de fundamentar con tesis en los escritos");
ok(!errores.length, "sin errores de JavaScript " + errores.join(" "));
await b.close();
