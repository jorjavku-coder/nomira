// Precios con carrito: la persona arma su plan en /precios, ve el total y recibe su cotización; abre la propuesta.
// Uso: node e2e/precios.mjs [url] [carpeta]   (Comercial > Configuración: «Publicar todos los precios con carrito»)
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
const { chromium } = createRequire(import.meta.url)("playwright");
const base = process.argv[2] || "http://localhost:3000";
const dir = process.argv[3] || "./capturas";
mkdirSync(dir, { recursive: true });
const ok = (c, m) => { if (!c) throw new Error("FALLÓ: " + m); console.log("ok  " + m); };
const b = await chromium.launch();
const errores = [];
const p = await b.newPage({ viewport: { width: 1366, height: 900 } });
p.on("console", (x) => x.type() === "error" && !/favicon|401|404|422/.test(x.text()) && errores.push(x.text()));
p.on("pageerror", (e) => errores.push(String(e)));
if (process.env.DEPURAR) p.on("request", (r) => r.url().includes("/api/precios") && r.method() === "POST" && console.log(r.url().split("/api")[1], r.postData()));
await p.goto(base + "/");
await p.getByRole("navigation", { name: "Secciones" }).getByRole("link", { name: "Precios" }).click();
await p.getByRole("heading", { name: /Arme su plan/ }).waitFor();
await p.getByText("Marque al menos un módulo").waitFor();
await p.getByRole("checkbox", { name: /Agenda/ }).check();
await p.getByRole("checkbox", { name: /Connect/ }).check();
await p.getByRole("checkbox", { name: /Prospectos|Leads/ }).first().check();
await p.getByRole("button", { name: "Agregar un usuario" }).click();
await p.locator("[data-prueba=total]").waitFor();
const t1 = await p.locator("[data-prueba=total]").innerText();
await p.getByRole("radio", { name: /anual/i }).click().catch(() => {});
await p.waitForTimeout(900);
await p.screenshot({ path: `${dir}/precios-01-carrito.png`, fullPage: true });
ok(/\$/.test(t1), "el carrito calcula el total: " + t1);
await p.getByLabel("Cupón").fill("NOEXISTE");
await p.getByRole("button", { name: "Aplicar" }).click();
await p.getByText(/cupón no existe/).waitFor();
ok(true, "un cupón inválido se rechaza");
await p.getByLabel("Cupón").fill("");
await p.getByRole("button", { name: "Comprar este plan" }).click();
await p.getByLabel("Su nombre").fill("Lic. Ana Ejemplo");
await p.getByLabel("Despacho o notaría").fill("Despacho Ejemplo Ficticio");
await p.getByLabel("Correo electrónico").fill("ana@despacho-ejemplo.test");
await p.getByRole("dialog").getByRole("checkbox").check();
await p.getByRole("button", { name: "Recibir mi cotización" }).click();
await p.getByRole("heading", { name: /Su cotización COT-/ }).waitFor({ timeout: 15000 }).catch(async (e) => { await p.screenshot({ path: `${dir}/precios-error.png` }); throw e; });
await p.screenshot({ path: `${dir}/precios-02-lista.png` });
ok(true, "recibe su cotización con folio");
await p.getByRole("link", { name: /Ver, aceptar y pagar/ }).click();
await p.waitForURL(/\/propuesta/);
await p.getByText(/COT-/).first().waitFor();
await p.waitForTimeout(800);
await p.screenshot({ path: `${dir}/precios-03-propuesta.png`, fullPage: true });
ok(true, "abre su propuesta para aceptarla y pagarla");
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto(base + "/precios");
await m.getByRole("checkbox", { name: /Agenda/ }).check();
await m.locator("[data-prueba=total]").waitFor();
await m.screenshot({ path: `${dir}/precios-04-celular.png`, fullPage: true });
ok(errores.length === 0, "sin errores en consola " + (errores.length ? JSON.stringify(errores.slice(0, 3)) : ""));
await b.close();
