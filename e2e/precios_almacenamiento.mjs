// Paquetes y precios: costo del disco de Render trasladado al precio del almacenamiento. Uso: node e2e/precios_almacenamiento.mjs [base] [capturas]
import { mkdirSync } from "node:fs";
const base = process.argv[2] || "http://localhost:3000";
const dir = process.argv[3] || "./capturas";
mkdirSync(dir, { recursive: true });
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
const ok = (c, m) => { if (!c) throw new Error("FALLÓ: " + m); console.log("ok  " + m); };
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 950 } });
const errores = []; p.on("pageerror", (e) => errores.push(String(e)));
await p.goto(base + "/plataforma/login");
await p.getByLabel(/Correo/).fill("dueno@nomira.test");
await p.getByLabel(/Contraseña/).first().fill("Panel-Nomira-2026");
await p.getByRole("button", { name: /Entrar/ }).click();
await p.getByRole("link", { name: "Comercial" }).click();
await p.getByRole("link", { name: "Paquetes y precios" }).click();
await p.getByText("1 GB te cuesta").waitFor();
ok(await p.getByText("$299.00").count() >= 1, "precio sugerido del bloque visible");
ok(await p.getByText(/te cuestan \$47\.50\/mes/).count() === 1, "costo del almacenamiento del Básico");
ok(await p.getByText("Curso propio adicional (Academia)").count() === 1, "precio del curso adicional");
await p.getByLabel("Tipo de cambio (MXN por dólar)").fill("20");
await p.getByLabel("Margen sobre el costo (%)").fill("100");
await p.getByRole("button", { name: "Guardar y recalcular" }).click();
await p.getByText("Costos de almacenamiento guardados.").waitFor();
await p.getByRole("button", { name: "Usar $259.00" }).waitFor();
ok(true, "recalcula el sugerido al cambiar tipo de cambio y margen");
await p.screenshot({ path: `${dir}/precios-almacenamiento.png`, fullPage: true });
ok(errores.length === 0, "sin errores " + errores.join("|"));
await b.close();
